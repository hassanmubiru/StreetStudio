// Upload N real videos through the API in enqueue-only mode (PROCESSING_INLINE=false),
// asserting they land `queued` (not processed inline). Writes context for the
// worker-drain phase.
import { readFileSync, writeFileSync } from "node:fs";

const BASE = "http://localhost:8080";
const COUNT = Number.parseInt(process.argv[2] ?? "2", 10);

async function j(method, path, { token, org, body, raw } = {}) {
  const headers = {};
  if (token) headers["authorization"] = `Bearer ${token}`;
  if (org) headers["x-organization-id"] = org;
  let payload;
  if (raw) {
    headers["content-type"] = "application/octet-stream";
    payload = raw;
  } else if (body) {
    headers["content-type"] = "application/json";
    payload = JSON.stringify(body);
  }
  const res = await fetch(BASE + path, { method, headers, body: payload });
  let data = null;
  try { data = await res.json(); } catch {}
  return { status: res.status, data };
}

const rand = () => Math.random().toString(36).slice(2, 10);

async function makeTenant() {
  const email = `w_${rand()}@example.com`;
  await j("POST", "/auth/register", { body: { email, password: "password12345", displayName: "W" } });
  const login = await j("POST", "/auth/login", { body: { email, password: "password12345" } });
  const token = login.data.accessToken;
  const org = await j("POST", "/organizations", { token, body: { name: "Org " + rand() } });
  return { token, orgId: org.data.id };
}

// Read the real sample video generated by ffmpeg (2 chunks).
const bytes = readFileSync("/tmp/worker-sample.mp4");
const half = Math.ceil(bytes.length / 2);
const part1 = bytes.subarray(0, half);
const part2 = bytes.subarray(half);

const A = await makeTenant();
console.log("org:", A.orgId, "sourceBytes:", bytes.length);

const videoIds = [];
for (let i = 0; i < COUNT; i++) {
  const create = await j("POST", "/uploads", { token: A.token, org: A.orgId, body: { totalParts: 2, contentType: "video/mp4" } });
  const id = create.data.id;
  await j("PUT", `/uploads/${id}/parts/1`, { token: A.token, org: A.orgId, raw: part1 });
  await j("PUT", `/uploads/${id}/parts/2`, { token: A.token, org: A.orgId, raw: part2 });
  const done = await j("POST", `/uploads/${id}/complete`, { token: A.token, org: A.orgId });
  console.log(`upload ${i + 1}: complete status=${done.status} processing=${done.data.processing} renditions=${done.data.renditions} videoId=${done.data.videoId}`);
  if (done.data.processing !== "queued") {
    console.log(`FAIL: expected processing=queued (enqueue-only), got ${done.data.processing}`);
    process.exit(1);
  }
  videoIds.push(done.data.videoId);
}

writeFileSync("/tmp/worker-ctx.json", JSON.stringify({ ...A, videoIds }, null, 2));
console.log("PASS: all uploads left videos queued (no inline processing).");
console.log("VIDEO_IDS=" + videoIds.join(","));
